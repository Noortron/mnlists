/**
 * App-wide Material 3 theme driven by the persisted [ThemeMode].
 *
 * [ThemeMode.SYSTEM] follows the device, [ThemeMode.LIGHT] and [ThemeMode.DARK]
 * override it. Because the mode is a `StateFlow` upstream, changing it in
 * Settings recomposes this function and every screen instantly.
 */
@Composable
fun MnlistsTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit,
) {
    val darkTheme = themeMode.isDark(isSystemInDarkTheme())

    // Keep system bar icons readable when the in-app override disagrees with
    // the device night-mode setting.
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = view.context.findActivity()?.window ?: return@SideEffect
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !darkTheme
                isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = MnlistsTypography,
        shapes = MnlistsShapes,
        content = content,
    )
}

private tailrec fun Context.findActivity(): Activity? = when (this) {
    is Activity -> this
    is ContextWrapper -> baseContext.findActivity()
    else -> null
}
